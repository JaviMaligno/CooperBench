"""Define what each restart policy carries between rounds."""

from cooperbench.agents._coop.territory import files_in_patch
from cooperbench.restart.feedback import format_feedback

POLICIES = ("iterate", "restart-fresh", "restart-informed", "agent-decides")


def _check(policy: str) -> None:
    if policy not in POLICIES:
        raise ValueError(f"unknown policy: {policy!r} (expected one of {POLICIES})")


def _concat_patches(patches: list[str]) -> str | None:
    """Concatenate an ordered list of patch deltas into a single composed patch.

    Each iterate round's saved diff is a delta over the previous committed tree
    (because apply_patch_in_container commits the starting patch before the agent
    runs). To reconstruct the full working tree from base we must stack all
    round deltas in order: delta_r1 || delta_r2 || ... || delta_rN.

    Strips trailing whitespace from each part and skips empty strings.
    Returns None if nothing survives.
    """
    parts = [p.rstrip("\n") for p in patches if p and p.strip()]
    if not parts:
        return None
    return "\n".join(parts) + "\n"


def starting_patch_for_round(policy: str, history: list[dict]) -> str | None:
    """Return the starting patch to apply before spawning a new round's agent.

    For iterate/agent-decides: returns the ordered concatenation of ALL history
    patches (delta stacking) so the container starts from the correct cumulative
    tree, not just the last round's delta.

    For restart-fresh/restart-informed: always returns None (fresh checkout).
    """
    _check(policy)
    if not history:
        return None
    if policy in ("iterate", "agent-decides"):
        patches = [h["patch"] for h in history]
        return _concat_patches(patches)
    return None


def informed_summary(history: list[dict]) -> str:
    lines = ["## Lessons from previous attempts (auto-generated by the harness)"]
    for h in history:
        t = h["tests"]
        total = t.get("tests_passed", 0) + t.get("tests_failed", 0)
        files = ", ".join(sorted(files_in_patch(h["patch"]))) or "(no files changed)"
        tail = (t.get("output", "") or "")[-500:]
        lines.append(
            f"### Attempt {h['round']}: {t.get('tests_passed', 0)}/{total} tests passed\n"
            f"Files touched: {files}\n"
            f"Failure tail:\n```\n{tail}\n```"
        )
    lines.append(
        "You are starting from a CLEAN CHECKOUT (none of the code above is "
        "present). Use the lessons; write a fresh implementation."
    )
    return "\n\n".join(lines)


def build_round_task(policy: str, base_task: str, history: list[dict]) -> str:
    _check(policy)
    if not history or policy == "restart-fresh":
        return base_task
    if policy == "restart-informed":
        return f"{base_task}\n\n{informed_summary(history)}"
    blocks = [format_feedback(h["tests"], h["round"]) for h in history]
    return (
        f"{base_task}\n\n## Previous attempts\n"
        f"Your WORKING TREE already contains your latest attempt; refine it.\n\n"
        + "\n".join(blocks)
    )
